"""PyTorch Dataset for synthetic palm-leaf restoration.

Loads (degraded, clean) image pairs generated by the degradation engine.
"""
import torch
from torch.utils.data import Dataset
from pathlib import Path
import cv2
import numpy as np
import json
from typing import Tuple, Optional, List
import albumentations as A
from albumentations.pytorch import ToTensorV2

from backend.core.logging import get_logger

logger = get_logger(__name__)


class PalmLeafRestorationDataset(Dataset):
    """Dataset for palm-leaf image restoration.

    Expects directory structure:
        data_dir/
            degraded_0000.jpg
            degraded_0001.jpg
            ...
            clean_0000.jpg
            clean_0001.jpg
            ...
            labels_0000.json
            labels_0001.json
            ...
    """

    def __init__(
        self,
        data_dir: str,
        split: str = "train",
        train_ratio: float = 0.8,
        image_size: Tuple[int, int] = (256, 256),
        augment: bool = True,
    ):
        """Initialize dataset.

        Args:
            data_dir: Directory containing degraded/clean image pairs
            split: "train" or "val"
            train_ratio: Fraction of data for training (rest for validation)
            image_size: Target image size (H, W)
            augment: Apply data augmentation
        """
        self.data_dir = Path(data_dir)
        self.split = split
        self.image_size = image_size
        self.augment = augment

        # Find all degraded images
        degraded_images = sorted(self.data_dir.glob("degraded_*.jpg"))

        if len(degraded_images) == 0:
            raise ValueError(f"No degraded_*.jpg images found in {data_dir}")

        # Split into train/val
        split_idx = int(len(degraded_images) * train_ratio)

        if split == "train":
            self.image_paths = degraded_images[:split_idx]
        else:  # val
            self.image_paths = degraded_images[split_idx:]

        # Verify clean images exist
        for degraded_path in self.image_paths[:5]:  # Check first 5
            clean_path = self._get_clean_path(degraded_path)
            if not clean_path.exists():
                raise ValueError(f"Clean image not found: {clean_path}")

        # Setup augmentations
        if augment and split == "train":
            self.transform = A.Compose([
                A.RandomCrop(height=image_size[0], width=image_size[1]),
                A.HorizontalFlip(p=0.5),
                A.Rotate(limit=5, p=0.3),
                A.Normalize(mean=[0.5], std=[0.5]),  # Normalize to [-1, 1]
                ToTensorV2(),
            ])
        else:
            self.transform = A.Compose([
                A.Resize(height=image_size[0], width=image_size[1]),
                A.Normalize(mean=[0.5], std=[0.5]),
                ToTensorV2(),
            ])

        logger.info(
            "dataset_initialized",
            split=split,
            num_samples=len(self.image_paths),
            image_size=image_size,
            augment=augment,
        )

    def _get_clean_path(self, degraded_path: Path) -> Path:
        """Get corresponding clean image path."""
        filename = degraded_path.name.replace("degraded_", "clean_")
        return degraded_path.parent / filename

    def __len__(self) -> int:
        return len(self.image_paths)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        """Get (degraded, clean) image pair.

        Returns:
            (degraded_tensor, clean_tensor) both (C, H, W) float32 in [-1, 1]
        """
        degraded_path = self.image_paths[idx]
        clean_path = self._get_clean_path(degraded_path)

        # Load images (as grayscale for now)
        degraded = cv2.imread(str(degraded_path), cv2.IMREAD_GRAYSCALE)
        clean = cv2.imread(str(clean_path), cv2.IMREAD_GRAYSCALE)

        if degraded is None or clean is None:
            raise ValueError(f"Failed to load images: {degraded_path}, {clean_path}")

        # Apply same transform to both images
        transformed = self.transform(image=degraded, mask=clean)
        degraded_tensor = transformed["image"]
        clean_tensor = transformed["mask"]

        # Add channel dimension if grayscale
        if len(degraded_tensor.shape) == 2:
            degraded_tensor = degraded_tensor.unsqueeze(0)
            clean_tensor = clean_tensor.unsqueeze(0)

        return degraded_tensor, clean_tensor


def get_dataloaders(
    data_dir: str,
    batch_size: int = 8,
    num_workers: int = 4,
    image_size: Tuple[int, int] = (256, 256),
    train_ratio: float = 0.8,
) -> Tuple[torch.utils.data.DataLoader, torch.utils.data.DataLoader]:
    """Create train and validation dataloaders.

    Args:
        data_dir: Directory containing synthetic data
        batch_size: Batch size
        num_workers: Number of workers for data loading
        image_size: Target image size
        train_ratio: Train/val split ratio

    Returns:
        (train_loader, val_loader)
    """
    train_dataset = PalmLeafRestorationDataset(
        data_dir=data_dir,
        split="train",
        train_ratio=train_ratio,
        image_size=image_size,
        augment=True,
    )

    val_dataset = PalmLeafRestorationDataset(
        data_dir=data_dir,
        split="val",
        train_ratio=train_ratio,
        image_size=image_size,
        augment=False,
    )

    train_loader = torch.utils.data.DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True,
    )

    val_loader = torch.utils.data.DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
    )

    logger.info(
        "dataloaders_created",
        train_size=len(train_dataset),
        val_size=len(val_dataset),
        batch_size=batch_size,
    )

    return train_loader, val_loader
